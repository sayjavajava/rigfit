package main

import (
	"encoding/json"
	"fmt"
	"net/url"
	"time"

	"github.com/sayjavajava/rigfit/internal/cache"
	"github.com/spf13/cobra"
)

const issueTrackerURL = "https://github.com/sayjavajava/rigfit/issues/new"

func newReportUnknownCmd() *cobra.Command {
	return &cobra.Command{
		Use:   "report-unknown",
		Short: "Write an anonymised hardware dump and print a pre-filled GitHub issue URL",
		Long: "report-unknown collects the same anonymised snapshot as `dump --anonymous`, " +
			"writes it to the cache directory, and prints a pre-filled GitHub issue URL so " +
			"unrecognised hardware can be reported as a test fixture (rigfit-BUILD-SPEC.md §10).",
		RunE: runReportUnknown,
	}
}

func runReportUnknown(cmd *cobra.Command, args []string) error {
	snap, err := buildSnapshot("")
	if err != nil {
		return fmt.Errorf("collecting hardware snapshot: %w", err)
	}

	body, err := json.MarshalIndent(snap, "", "  ")
	if err != nil {
		return err
	}

	filename := fmt.Sprintf("report-unknown-%d.json", time.Now().Unix())
	if err := cache.WriteFile(body, filename); err != nil {
		return fmt.Errorf("writing hardware dump: %w", err)
	}
	path, err := cache.Path(filename)
	if err != nil {
		return err
	}

	out := cmd.OutOrStdout()
	if _, err := fmt.Fprintf(out, "Wrote anonymised hardware dump to %s\n", path); err != nil {
		return err
	}
	if !snap.hasUnknown() {
		if _, err := fmt.Fprintln(out, "Note: every detected part resolved to a known identity; this fixture is still useful for regression coverage."); err != nil {
			return err
		}
	}
	_, err = fmt.Fprintf(out, "Pre-filled issue: %s\n", buildIssueURL(snap, body))
	return err
}

func buildIssueURL(snap snapshot, body []byte) string {
	title := "Hardware report"
	if snap.hasUnknown() {
		title = fmt.Sprintf("Hardware report: unrecognised device on %s/%s", snap.OS, snap.Arch)
	}
	issueBody := "<!-- generated by `rigfit report-unknown` -->\n\n```json\n" + string(body) + "\n```\n"

	v := url.Values{}
	v.Set("title", title)
	v.Set("body", issueBody)
	v.Set("labels", "hardware-report")
	return issueTrackerURL + "?" + v.Encode()
}
